export type Phase = 1 | 2 | 3;
export type ApplyStatus = 'planned' | 'in-progress' | 'applied' | 'verified' | 'out-of-scope';

export interface SurveyItem {
  id: string;
  name: string;
  scope: 'gestalt' | 'orca-plugin-external';
  visuals: string;
  motions: string;
  candidate: string;
  /** 이 조사 항목이 나뉘어 들어간 실제 화면 ID. 범위 밖이면 빈 배열 */
  screens: string[];
}

export interface ScreenBaseline {
  /** 바꾸면 안 되는 값과 단위, 출처 위치, 상태, 이벤트 순서 */
  preserve: string[];
  /** 전환 뒤에도 같은 결과가 나와야 하는 핵심 조작 */
  operations: string[];
}

export interface ScreenEntry {
  id: string;
  name: string;
  phase: Phase;
  survey: string;
  files: string[];
  /** 정상 생성 경로. 검증은 이 경로로 만든 산출물로 한다 */
  entry: string;
  colorRoles: string[];
  visuals: string[];
  motions: string[];
  baseline: ScreenBaseline;
  /** 출력 형식이나 호스트가 정하는 제약 */
  constraints: string[];
  evidence: string[];
  status: ApplyStatus;
}

